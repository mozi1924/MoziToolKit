#!/usr/bin/env python3
"""
Generate the Python mesh-attribute schema mirror from the native libmtk core.

The Rust core (`mtk-core::attributes`) is the single authoritative source for
attribute names, domains, data types, roles, and the retired-attribute list.
This tool mirrors that schema into `bridge/mesh/_attribute_schema_generated.py`
so mock/UI code can run without importing the native extension.

Usage:
    python tools/sync_attribute_schema.py          # rewrite the mirror
    python tools/sync_attribute_schema.py --check  # fail if the mirror is stale
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parent.parent
PARENT_DIR = PROJECT_DIR.parent
OUTPUT_PATH = PROJECT_DIR / "bridge" / "mesh" / "_attribute_schema_generated.py"

for _path in (PROJECT_DIR, PARENT_DIR):
    if str(_path) not in sys.path:
        sys.path.insert(0, str(_path))


def _load_native_schema() -> tuple[list[tuple[str, str, str, str]], list[str]]:
    # Load the dev loader by path: importing the MoziToolKit package would pull
    # in bpy-dependent operators before bpy is available in a plain Python run.
    import importlib.util

    loader_path = PROJECT_DIR / "dev" / "loader.py"
    spec = importlib.util.spec_from_file_location("mtk_dev_loader", loader_path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Cannot load {loader_path}")
    loader = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(loader)

    if not loader.setup_dev_environment():
        raise RuntimeError("Cannot mount the native libmtk_py extension (dev/lib or target/release)")

    import libmtk_py as mtk

    if not hasattr(mtk, "mesh_attribute_schema") or not hasattr(mtk, "retired_mesh_attributes"):
        raise RuntimeError(
            "libmtk_py does not expose the mesh attribute schema; "
            "rebuild the extension with 'cargo build-py'"
        )

    specs = [tuple(item) for item in mtk.mesh_attribute_schema()]
    retired = list(mtk.retired_mesh_attributes())
    return specs, retired


def _constant_name(attribute_name: str) -> str:
    if not attribute_name.startswith("mtk_"):
        raise ValueError(f"attribute is not namespaced with mtk_: {attribute_name}")
    return "ATTR_" + attribute_name[len("mtk_"):].upper()


def _render(specs: list[tuple[str, str, str, str]], retired: list[str]) -> str:
    payload = json.dumps(
        {"specs": [list(spec) for spec in specs], "retired": retired},
        sort_keys=True,
        separators=(",", ":"),
    )
    digest = hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]

    lines = [
        '"""AUTO-GENERATED by tools/sync_attribute_schema.py. DO NOT EDIT.',
        "",
        "Source of truth: mtk-core::attributes::{MESH_ATTRIBUTE_SPECS, RETIRED_MESH_ATTRIBUTES}.",
        "Regenerate after changing the native attribute contract:",
        "    python tools/sync_attribute_schema.py",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        f'SCHEMA_HASH = "{digest}"',
        "",
        "# (name, domain, data_type, role)",
        "ATTRIBUTE_SPECS: tuple[tuple[str, str, str, str], ...] = (",
    ]
    for name, domain, data_type, role in specs:
        lines.append(f'    ("{name}", "{domain}", "{data_type}", "{role}"),')
    lines += [
        ")",
        "",
        "RETIRED_ATTRIBUTE_NAMES: frozenset[str] = frozenset({",
    ]
    for name in retired:
        lines.append(f'    "{name}",')
    lines += [
        "})",
        "",
        "# Convenience constants for shader/host code. One name, one definition.",
    ]
    for name, _domain, _data_type, _role in specs:
        lines.append(f'{_constant_name(name)} = "{name}"')
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero when the checked-in mirror differs from the native schema.",
    )
    args = parser.parse_args()

    specs, retired = _load_native_schema()
    rendered = _render(specs, retired)

    if args.check:
        if not OUTPUT_PATH.is_file():
            print(f"Missing generated schema: {OUTPUT_PATH}", file=sys.stderr)
            return 1
        current = OUTPUT_PATH.read_text(encoding="utf-8")
        if current != rendered:
            print(
                "Attribute schema mirror is stale; run "
                "'python tools/sync_attribute_schema.py'.",
                file=sys.stderr,
            )
            return 1
        print("Attribute schema mirror is up to date.")
        return 0

    OUTPUT_PATH.write_text(rendered, encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH.relative_to(PROJECT_DIR)} ({len(specs)} active, {len(retired)} retired).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
