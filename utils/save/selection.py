"""
MoziToolKit Yefira Selection Ingestion Helper.

Provides headless parsing and normalization of `yefira_selection.json`
generated by the Yefira Live Sync Minecraft mod.
"""

from __future__ import annotations

import json
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, Optional, Tuple

logger = logging.getLogger("MoziToolKit.Utils.Save.Selection")

YEFIRA_SELECTION_FILENAME = "yefira_selection.json"


@dataclass(frozen=True)
class YefiraSelection:
    """Canonical 3D selection imported from Yefira mod storage."""

    pos1: Tuple[int, int, int]
    pos2: Tuple[int, int, int]
    min_coord: Tuple[int, int, int]
    max_coord: Tuple[int, int, int]
    dimension: str
    raw_dimension: str
    size: Tuple[int, int, int]
    volume: int


def normalize_dimension(raw_dim: Optional[str]) -> str:
    """
    Normalizes a Minecraft dimension identifier to the standard identifier,
    preserving custom namespaces.

    Examples:
        'minecraft:overworld' / 'overworld' -> 'overworld'
        'minecraft:the_nether' / 'the_nether' / 'nether' -> 'the_nether'
        'minecraft:the_end' / 'the_end' / 'end' -> 'the_end'
        'twilightforest:twilight_forest' -> 'twilightforest:twilight_forest'
        None / '' -> 'overworld'
    """
    if not raw_dim or not isinstance(raw_dim, str):
        return "overworld"

    dim = raw_dim.strip().lower()
    if not dim:
        return "overworld"

    if dim in ("overworld", "minecraft:overworld"):
        return "overworld"
    if dim in ("nether", "the_nether", "minecraft:the_nether"):
        return "the_nether"
    if dim in ("end", "the_end", "minecraft:the_end"):
        return "the_end"

    return dim


def resolve_world_directory(path: str | Path | None) -> Optional[Path]:
    """
    Resolves the root directory of a Minecraft save from a folder or file path.

    Handles paths pointing to:
    - The world root folder directly
    - A file inside the world folder (e.g. level.dat, yefira_selection.json)
    - Standard world subfolders (e.g. region/, entities/, poi/)
    """
    if not path:
        return None

    try:
        p = Path(path).resolve()
    except Exception:
        return None

    if p.is_file():
        p = p.parent

    if not p.exists():
        return None

    # If the folder itself contains level.dat or yefira_selection.json, it's the root
    if (p / YEFIRA_SELECTION_FILENAME).exists() or (p / "level.dat").exists():
        return p

    # If the parent contains level.dat or yefira_selection.json (e.g. user selected 'region/')
    parent = p.parent
    if parent and parent != p:
        if (parent / YEFIRA_SELECTION_FILENAME).exists() or (parent / "level.dat").exists():
            return parent

    return p


def load_yefira_selection(path: str | Path | None) -> Optional[YefiraSelection]:
    """
    Loads and normalizes Yefira selection data from the given save folder or path.

    Returns None if the file does not exist or cannot be parsed.
    """
    world_dir = resolve_world_directory(path)
    if not world_dir:
        return None

    selection_file = world_dir / YEFIRA_SELECTION_FILENAME
    if not selection_file.is_file():
        return None

    try:
        data = json.loads(selection_file.read_text(encoding="utf-8"))
    except Exception as exc:
        logger.warning("Failed to read %s: %s", selection_file, exc)
        return None

    if not isinstance(data, dict):
        return None

    p1_raw = data.get("pos1")
    p2_raw = data.get("pos2")
    if not isinstance(p1_raw, dict) or not isinstance(p2_raw, dict):
        return None

    try:
        p1 = (int(p1_raw["x"]), int(p1_raw["y"]), int(p1_raw["z"]))
        p2 = (int(p2_raw["x"]), int(p2_raw["y"]), int(p2_raw["z"]))
    except (KeyError, ValueError, TypeError) as exc:
        logger.warning("Invalid pos1/pos2 coordinate data in %s: %s", selection_file, exc)
        return None

    min_coord = (
        min(p1[0], p2[0]),
        min(p1[1], p2[1]),
        min(p1[2], p2[2]),
    )
    max_coord = (
        max(p1[0], p2[0]),
        max(p1[1], p2[1]),
        max(p1[2], p2[2]),
    )

    raw_dim = data.get("dimension")
    dim_str = str(raw_dim) if raw_dim is not None else "minecraft:overworld"
    dimension = normalize_dimension(dim_str)

    dx = max_coord[0] - min_coord[0] + 1
    dy = max_coord[1] - min_coord[1] + 1
    dz = max_coord[2] - min_coord[2] + 1
    volume = dx * dy * dz

    return YefiraSelection(
        pos1=p1,
        pos2=p2,
        min_coord=min_coord,
        max_coord=max_coord,
        dimension=dimension,
        raw_dimension=dim_str,
        size=(dx, dy, dz),
        volume=volume,
    )


__all__ = [
    "YEFIRA_SELECTION_FILENAME",
    "YefiraSelection",
    "normalize_dimension",
    "resolve_world_directory",
    "load_yefira_selection",
]
